"""
Data Preprocessing Pipeline Module for Credit Scoring Model.
Handles dataset loading, target encoding, stratified splitting, and ColumnTransformer pipeline creation.
"""

import os
import sys
import pandas as pd
import numpy as np
from typing import Tuple, List, Dict, Any
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DATA_PATH = os.path.join(PROJECT_ROOT, 'data', 'credit_dataset.csv')

if __package__:
    from . import feature_engineering
else:
    import feature_engineering

sys.modules.setdefault('feature_engineering', feature_engineering)
FinancialFeatureEngineer = feature_engineering.FinancialFeatureEngineer

# Original feature taxonomy
NUMERICAL_FEATURES_ORIGINAL: List[str] = [
    'duration',
    'credit_amount',
    'installment_commitment',
    'residence_since',
    'age',
    'existing_credits',
    'num_dependents'
]

# Engineered numerical features generated by FinancialFeatureEngineer
ENGINEERED_NUMERICAL_FEATURES: List[str] = [
    'monthly_payment_burden',
    'credit_to_age_ratio',
    'high_burden_flag',
    'liquidity_buffer_score',
    'stability_composite'
]

ALL_NUMERICAL_FEATURES: List[str] = NUMERICAL_FEATURES_ORIGINAL + ENGINEERED_NUMERICAL_FEATURES

CATEGORICAL_FEATURES: List[str] = [
    'checking_status',
    'credit_history',
    'purpose',
    'savings_status',
    'employment',
    'personal_status',
    'other_parties',
    'property_magnitude',
    'other_payment_plans',
    'housing',
    'job',
    'own_telephone',
    'foreign_worker'
]

TARGET_COLUMN = 'class'


def load_dataset(filepath: str) -> pd.DataFrame:
    """
    Loads credit dataset from CSV, performs integrity assertions, and returns DataFrame.
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Dataset file not found at: {filepath}")
    
    df = pd.read_csv(filepath)
    if TARGET_COLUMN not in df.columns:
        raise ValueError(f"Target column '{TARGET_COLUMN}' missing from dataset at {filepath}")
    
    return df


def encode_target(y: pd.Series) -> pd.Series:
    """
    Encodes binary credit risk target:
    - 'bad' -> 1 (High Credit Risk / Positive Class)
    - 'good' -> 0 (Low Credit Risk / Negative Class)
    """
    mapping = {'bad': 1, 'good': 0}
    encoded = y.map(mapping)
    if encoded.isnull().any():
        raise ValueError("Target contains unrecognized classes outside of {'good', 'bad'}")
    return encoded.astype(int)


def decode_target(y_encoded: np.ndarray) -> np.ndarray:
    """
    Decodes binary predictions back to descriptive string categories.
    """
    mapping = {1: 'Bad Credit / Higher Credit Risk', 0: 'Good Credit / Lower Credit Risk'}
    return np.array([mapping.get(val, 'Unknown') for val in y_encoded])


def build_preprocessor_pipeline() -> Pipeline:
    """
    Constructs a leakage-free Scikit-Learn Pipeline combining:
    1. FinancialFeatureEngineer (domain transformation)
    2. ColumnTransformer:
       - Numerical features: Median Imputation + StandardScaler
       - Categorical features: Most Frequent Imputation + OneHotEncoder
    """
    num_pipeline = Pipeline([
        ('imputer', SimpleImputer(strategy='median')),
        ('scaler', StandardScaler())
    ])

    cat_pipeline = Pipeline([
        ('imputer', SimpleImputer(strategy='most_frequent')),
        ('encoder', OneHotEncoder(handle_unknown='ignore', sparse_output=False))
    ])

    col_transformer = ColumnTransformer(
        transformers=[
            ('num', num_pipeline, ALL_NUMERICAL_FEATURES),
            ('cat', cat_pipeline, CATEGORICAL_FEATURES)
        ],
        remainder='drop'
    )

    full_preprocessor = Pipeline([
        ('feature_engineer', FinancialFeatureEngineer()),
        ('transformer', col_transformer)
    ])

    return full_preprocessor


def prepare_train_test_split(
    df: pd.DataFrame, 
    test_size: float = 0.2, 
    random_state: int = 42
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]:
    """
    Performs a stratified split to maintain the 70/30 class proportion across train and test sets.
    """
    X = df.drop(columns=[TARGET_COLUMN])
    y = encode_target(df[TARGET_COLUMN])

    X_train, X_test, y_train, y_test = train_test_split(
        X, y,
        test_size=test_size,
        stratify=y,
        random_state=random_state
    )

    return X_train, X_test, y_train, y_test


if __name__ == '__main__':
    data_path = DEFAULT_DATA_PATH
    df = load_dataset(data_path)
    X_train, X_test, y_train, y_test = prepare_train_test_split(df)
    print(f"Data successfully split:")
    print(f"Train samples: {X_train.shape[0]} (High-risk: {y_train.sum()}, Low-risk: {(y_train == 0).sum()})")
    print(f"Test samples:  {X_test.shape[0]} (High-risk: {y_test.sum()}, Low-risk: {(y_test == 0).sum()})")
    
    preprocessor = build_preprocessor_pipeline()
    X_train_trans = preprocessor.fit_transform(X_train)
    X_test_trans = preprocessor.transform(X_test)
    print(f"Transformed train shape: {X_train_trans.shape}")
    print(f"Transformed test shape:  {X_test_trans.shape}")
